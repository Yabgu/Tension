#!/usr/bin/env node
// GENERATED-FILE PRODUCER for the OGRE wire records.
//
// One source (`schema/ogre.json`) → two declarations:
//
//   tension-framework/assembly/ogre/generated/ogre.generated.ts   (the guest)
//   tension-ogre/src/generated/ogre.generated.h                   (the host)
//
// The layout is COMPUTED from field widths, never read back from a compiler.
// The alignment rule is the wire's own: f32/u32/i32 occupy 4 and align to 4,
// u64 occupies 8 and aligns to 8, a nested record occupies its computed size
// and aligns to the maximum alignment of its fields. That is what the guest
// compiler produces, so the .h reproduces the wire bytes exactly — which is
// why the header is NOT wrapped in `#pragma pack(1)`: packing would remove the
// 4-byte pads the wire has (LightRecord.reserved at 80, CameraRecord.reserved
// at 64, Resource.seq at 40) and shrink three records below their wire size.
// Measured, 2026-10-30: natural 88/80/48, packed 84/76/44.
//
// The static_asserts this emits are the drift guard on the host side: every
// field's offset and every record's size, computed here and checked by the
// C++ compiler. A change to the schema that the C++ layout does not reproduce
// fails the build rather than mis-decoding a scene.
//
// Usage:
//   node tools/codegen/generate.mjs \
//     --schema schema/ogre.json \
//     --out-ts tension-framework/assembly/ogre/generated \
//     --out-h  tension-ogre/src/generated
//
//   node tools/codegen/generate.mjs ... --check
//     Regenerates into a temporary directory and diffs against the committed
//     files. Exits 1 on drift, so a schema edit that was not regenerated
//     fails the test suite.

import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { tmpdir } from "node:os";

const TS_NAME = "ogre.generated.ts";
const H_NAME = "ogre.generated.h";
const BANNER = "// GENERATED BY tools/codegen — DO NOT EDIT.";

/** Width and alignment of a scalar field type, in the wire's model. */
const SCALARS = {
  u8: { ts: "u8", c: "uint8_t", size: 1, align: 1 },
  i8: { ts: "i8", c: "int8_t", size: 1, align: 1 },
  u16: { ts: "u16", c: "uint16_t", size: 2, align: 2 },
  i16: { ts: "i16", c: "int16_t", size: 2, align: 2 },
  u32: { ts: "u32", c: "uint32_t", size: 4, align: 4 },
  i32: { ts: "i32", c: "int32_t", size: 4, align: 4 },
  f32: { ts: "f32", c: "float", size: 4, align: 4 },
  u64: { ts: "u64", c: "uint64_t", size: 8, align: 8 },
  i64: { ts: "i64", c: "int64_t", size: 8, align: 8 },
};

const alignUp = (n, a) => (n + a - 1) - ((n + a - 1) % a);

/** camelCase → snake_case, the one naming rule between the two sides. */
function snake(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
}

/**
 * Lay out every record in dependency order.
 * Returns a Map name → { record, size, align, offsets: Map(field → offset) }.
 */
function layout(schema) {
  const byName = new Map();
  const out = new Map();
  for (const rec of schema.records) byName.set(rec.name, rec);

  const resolve = (name, stack) => {
    if (out.has(name)) return out.get(name);
    const rec = byName.get(name);
    if (!rec) throw new Error(`unknown field type '${name}'`);
    if (stack.includes(name)) throw new Error(`nested cycle through '${name}'`);

    let cursor = 0;
    let align = 1;
    const offsets = new Map();
    for (const field of rec.fields) {
      const scalar = SCALARS[field.type];
      const size = scalar ? scalar.size : resolve(field.type, [...stack, name]).size;
      const fieldAlign = scalar ? scalar.align : resolve(field.type, [...stack, name]).align;
      cursor = alignUp(cursor, fieldAlign);
      offsets.set(field.name, cursor);
      cursor += size;
      if (fieldAlign > align) align = fieldAlign;
    }
    const size = alignUp(cursor, align);
    const built = { record: rec, size, align, offsets, fields: rec.fields };
    out.set(name, built);
    return built;
  };

  for (const rec of schema.records) resolve(rec.name, []);

  // A `checks` block restates offsets the layout just computed. That is
  // deliberate duplication inside the schema, and it is checked here rather than
  // trusted: a hand edit to an offset, or a field order change that was not
  // mirrored, fails generation instead of emitting a check that agrees with
  // itself.
  for (const rec of schema.records) {
    const checks = rec.checks;
    if (!checks) continue;
    const built = out.get(rec.name);
    if (checks.sizeof != null && checks.sizeof !== built.size) {
      throw new Error(
        `${rec.name}: checks.sizeof is ${checks.sizeof} but the layout computes ${built.size}`
      );
    }
    for (const check of checks.fields ?? []) {
      const computed = built.offsets.get(check.name);
      if (computed == null) throw new Error(`${rec.name}: checks names unknown field '${check.name}'`);
      if (check.offset != null && check.offset !== computed) {
        throw new Error(
          `${rec.name}.${check.name}: checks says offset ${check.offset} but the layout computes ${computed}`
        );
      }
    }
    if (checks.tail) {
      const field = rec.fields.find((f) => f.name === checks.tail);
      if (!field) throw new Error(`${rec.name}: checks.tail names unknown field '${checks.tail}'`);
      if (SCALARS[field.type]) {
        throw new Error(`${rec.name}: checks.tail must name a nested field, not a scalar`);
      }
    }
  }
  return out;
}

/** The generated .ts: plain `struct` for value twins, `@unmanaged` for views. */
function emitTs(schema, layoutMap) {
  const lines = [
    BANNER,
    "//",
    "// Source: schema/ogre.json. Regenerate with `node tools/codegen/generate.mjs`;",
    "// `--check` fails the test suite when the two disagree.",
    "//",
    "// The record shapes are the wire's. The static constructors are emitted here",
    "// because they must live on the type (66 call sites use them) and the",
    "// generator is the only thing that may write this file.",
    "",
  ];
  for (const imp of schema.tsImports ?? []) {
    lines.push(`import { ${imp.names.join(", ")} } from "${imp.from}";`);
    if (imp.why) lines.push(`// ${imp.why}`);
    lines.push("");
  }
  for (const rec of schema.records) {
    const built = layoutMap.get(rec.name);
    lines.push(`/** ${rec.name} — ${built.size} bytes, alignment ${built.align}. */`);
    if (rec.kind === "view") lines.push("@unmanaged");
    lines.push(`export struct ${rec.name} {`);
    for (const field of rec.fields) {
      const scalar = SCALARS[field.type];
      const decl = scalar
        ? `${field.name}: ${scalar.ts} = 0;`
        : `${field.name}: ${field.type} = {};`;
      lines.push(`  ${decl}`);
    }
    if (rec.statics) {
      lines.push("");
      lines.push(rec.statics);
    }
    lines.push("}");
    lines.push("");
  }
  // The guest-side record checks, emitted from each record's `checks` block.
  // They keep the hand-written contract exactly: a string naming the first
  // disagreeing field, or null. What they now compare is the *compiler's* layout
  // of the generated struct against the *schema's* computed offsets, so a
  // compiler whose alignment disagrees with the wire fails a fixture at startup.
  for (const rec of schema.records) {
    const checks = rec.checks;
    if (!checks) continue;
    const built = layoutMap.get(rec.name);
    const fn = checks.function;
    lines.push(`/**`);
    lines.push(` * Where this build's \`${rec.name}\` disagrees with \`schema/ogre.json\`, or \`null\`.`);
    lines.push(` *`);
    lines.push(` * Generated: the offsets are the schema's, the layout is the compiler's.`);
    lines.push(` */`);
    lines.push(`export function ${fn}(): string | null {`);
    for (const check of checks.fields ?? []) {
      const offset = check.offset ?? built.offsets.get(check.name);
      const field = rec.fields.find((f) => f.name === check.name);
      const isScalar = Boolean(SCALARS[field.type]);
      const lhs = isScalar
        ? `offsetof<${rec.name}>("${check.name}")`
        : `offsetof<${rec.name}>("${check.name}") + offsetof<${field.type}>("x")`;
      lines.push(`  if (${lhs} != ${offset}) {`);
      lines.push(`    return "${rec.name}.${check.name}";`);
      lines.push(`  }`);
    }
    if (checks.tail) {
      const field = rec.fields.find((f) => f.name === checks.tail);
      lines.push(`  if (offsetof<${rec.name}>("${checks.tail}") + sizeof<${field.type}>() != sizeof<${rec.name}>()) {`);
      lines.push(`    return "${rec.name} tail";`);
      lines.push(`  }`);
    }
    if (checks.sizeof != null) {
      lines.push(`  if (sizeof<${rec.name}>() != ${checks.sizeof}) return "${rec.name} size";`);
    }
    lines.push(`  return null;`);
    lines.push(`}`);
    lines.push("");
  }

  return lines.join("\n").replace(/\n+$/, "\n");
}

/** The generated .h: full-width packed-free structs plus computed asserts. */
function emitH(schema, layoutMap) {
  const lines = [
    BANNER,
    "//",
    "// Source: schema/ogre.json. Full-width: each struct is the wire record, not a",
    "// prefix of it, so one memcpy decodes one record.",
    "//",
    "// No `#pragma pack`: the wire's layout IS the naturally aligned one. Packing",
    "// would delete the 4-byte pads the wire carries before each u64 that follows",
    "// u32s (LightRecord.reserved, CameraRecord.reserved, Resource.seq) and shrink",
    "// those records by 4 bytes.",
    "",
    "#ifndef TENSION_OGRE_GENERATED_OGRE_GENERATED_H",
    "#define TENSION_OGRE_GENERATED_OGRE_GENERATED_H",
    "",
    "#include <cstddef>",
    "#include <cstdint>",
    "",
    "namespace tension_ogre {",
    "",
  ];
  for (const rec of schema.records) {
    const built = layoutMap.get(rec.name);
    lines.push(`/// ${rec.name} — ${built.size} bytes on the wire.`);
    lines.push(`struct ${rec.name} {`);
    for (const field of rec.fields) {
      const scalar = SCALARS[field.type];
      const ctype = scalar ? scalar.c : field.type;
      lines.push(`    ${ctype} ${snake(field.name)}${scalar ? " = 0" : " = {}"};`);
    }
    lines.push("};");
    lines.push("");
  }
  lines.push("// Every offset and size the schema computed, checked by the C++ compiler.");
  lines.push("// A field that moves, or a record that changes width, fails the build here.");
  for (const rec of schema.records) {
    const built = layoutMap.get(rec.name);
    for (const field of rec.fields) {
      lines.push(
        `static_assert(offsetof(${rec.name}, ${snake(field.name)}) == ${built.offsets.get(field.name)}, ` +
        `"${rec.name}.${snake(field.name)} must be at the wire offset ${built.offsets.get(field.name)}");`
      );
    }
    lines.push(`static_assert(sizeof(${rec.name}) == ${built.size}, "${rec.name} is ${built.size} bytes on the wire");`);
    lines.push("");
  }
  lines.push("} // namespace tension_ogre");
  lines.push("");
  lines.push("#endif");
  lines.push("");
  return lines.join("\n");
}

function parseArgs(argv) {
  const out = { check: false };
  for (let i = 0; i < argv.length; ++i) {
    const a = argv[i];
    if (a === "--check") { out.check = true; continue; }
    if (a === "--schema") { out.schema = argv[++i]; continue; }
    if (a === "--out-ts") { out.outTs = argv[++i]; continue; }
    if (a === "--out-h") { out.outH = argv[++i]; continue; }
    throw new Error(`unknown argument '${a}'`);
  }
  if (!out.schema || !out.outTs || !out.outH) {
    throw new Error("usage: generate.mjs --schema <file> --out-ts <dir> --out-h <dir> [--check]");
  }
  return out;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const schema = JSON.parse(readFileSync(args.schema, "utf8"));
  const layoutMap = layout(schema);
  const ts = emitTs(schema, layoutMap);
  const h = emitH(schema, layoutMap);

  if (args.check) {
    const stage = mkdtempSync(join(tmpdir(), "ogre-codegen-"));
    try {
      writeFileSync(join(stage, TS_NAME), ts);
      writeFileSync(join(stage, H_NAME), h);
      let drift = 0;
      for (const [dir, name, text] of [[args.outTs, TS_NAME, ts], [args.outH, H_NAME, h]]) {
        let committed;
        try {
          committed = readFileSync(join(dir, name), "utf8");
        } catch {
          console.error(`codegen --check: ${join(dir, name)} is missing`);
          ++drift;
          continue;
        }
        if (committed !== text) {
          console.error(`codegen --check: ${join(dir, name)} is out of date — re-run tools/codegen/generate.mjs`);
          ++drift;
        }
      }
      if (drift) process.exit(1);
      console.log("codegen --check: generated files are up to date");
      return;
    } finally {
      rmSync(stage, { recursive: true, force: true });
    }
  }

  mkdirSync(args.outTs, { recursive: true });
  mkdirSync(args.outH, { recursive: true });
  writeFileSync(join(args.outTs, TS_NAME), ts);
  writeFileSync(join(args.outH, H_NAME), h);

  const summary = schema.records
    .map((r) => `${r.name}=${layoutMap.get(r.name).size}`)
    .join(" ");
  console.log(`codegen: ${schema.records.length} records -> ${TS_NAME}, ${H_NAME}`);
  console.log(`codegen: sizes ${summary}`);
}

main();
