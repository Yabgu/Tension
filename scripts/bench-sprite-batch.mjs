#!/usr/bin/env node
// scripts/bench-sprite-batch.mjs — build and run the 2D sprite-batch probe.
//
// The probe is not linked into anything. It exists to re-measure the per-bucket
// cost `docs/modules/2d.md` §5 budgets against, so the page cites a file in this tree
// rather than a number from a planning conversation it cannot reproduce.
//
// Steps: compile the two shaders to SPIR-V, compile sprite_batch.c against
// SDL3, run it headless, and print its table. `--write-results` adds the host
// line and writes tension-2d/bench/results.txt.
//
// Usage:
//   node scripts/bench-sprite-batch.mjs [--write-results]

import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync, existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import os from 'node:os';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BENCH = join(ROOT, 'tension-2d', 'bench');
const SHADERS = join(BENCH, 'shaders');
const OUT = join(BENCH, 'build');

function die(msg) {
    console.error(`bench-sprite-batch: ${msg}`);
    process.exit(1);
}

function have(cmd) {
    const r = spawnSync(cmd, ['--version'], { encoding: 'utf8' });
    return r.status === 0 || r.status === 1; // glslangValidator exits 1 on --version
}

function sdlFlags() {
    try {
        const cflags = execFileSync('pkg-config', ['--cflags', 'sdl3'], { encoding: 'utf8' }).trim();
        const libs = execFileSync('pkg-config', ['--libs', 'sdl3'], { encoding: 'utf8' }).trim();
        return { cflags, libs };
    } catch {
        die('pkg-config sdl3 not found — SDL3 is a build prerequisite (`docs/modules/2d.md` §1)');
    }
}

mkdirSync(OUT, { recursive: true });

// ── 1. Shaders ───────────────────────────────────────────────────────────────
for (const [src, stage] of [['sprite.vert', 'vert'], ['sprite.frag', 'frag']]) {
    const input = join(SHADERS, src);
    const output = join(OUT, `${src}.spv`);
    if (!existsSync(input)) die(`missing shader ${input}`);
    try {
        execFileSync('glslangValidator', ['-V', '--target-env', 'vulkan1.0', '-S', stage, input, '-o', output], {
            stdio: 'pipe',
        });
        console.log(`shader  ${src} -> ${src}.spv`);
    } catch (e) {
        console.error(String(e.stderr ?? e));
        die(`glslangValidator failed on ${src}`);
    }
}

// ── 2. Probe binary ──────────────────────────────────────────────────────────
const { cflags, libs } = sdlFlags();
const binary = join(OUT, 'sprite_batch');
const cc = process.env.CC || 'cc';
const compile = spawnSync(
    cc,
    ['-O2', '-o', binary, join(BENCH, 'sprite_batch.c'), ...(cflags ? cflags.split(' ') : []), ...(libs ? libs.split(' ') : []), '-lm'],
    { encoding: 'utf8' },
);
if (compile.status !== 0) {
    console.error(compile.stdout, compile.stderr);
    die('compilation failed');
}
console.log(`built   ${binary}`);

// ── 3. Run ───────────────────────────────────────────────────────────────────
const run = spawnSync(binary, ['--spv', OUT], {
    encoding: 'utf8',
    env: { ...process.env, SDL_VIDEODRIVER: 'offscreen' },
});
if (run.status !== 0) {
    console.error(run.stdout, run.stderr);
    die(`probe exited ${run.status}`);
}

const table = run.stdout.trim();
console.log(`\n${table}\n`);

// ── 4. Optionally record it ──────────────────────────────────────────────────
if (process.argv.includes('--write-results')) {
    const sdlVersion = execFileSync('pkg-config', ['--modversion', 'sdl3'], { encoding: 'utf8' }).trim();
    const date = new Date().toISOString().slice(0, 10);
    // The Vulkan ICD is the thing that decides whether these numbers describe a
    // GPU. SDL reports the driver family ("vulkan"), not the implementation, so
    // record the ICD alongside it.
    const icdDir = '/usr/share/vulkan/icd.d';
    let icd = 'none found';
    try {
        const files = readdirSync(icdDir).filter((f) => f.endsWith('.json'));
        icd = files.length ? files.join(', ') : 'none';
    } catch { /* not a Vulkan host */ }
    const header = [
        '// Generated by scripts/bench-sprite-batch.mjs --write-results',
        '// Re-run it rather than trusting these numbers on another host.',
        `date: ${date}`,
        `host: ${os.platform()} ${os.release()} ${os.arch()}`,
        `hostname: ${os.hostname()}`,
        `cpu: ${os.cpus()[0]?.model ?? 'unknown'} x${os.cpus().length}`,
        `sdl: ${sdlVersion}`,
        `vulkan_icd: ${icd}`,
        '',
    ].join('\n');
    const body = table
        .split('\n')
        .map((line) => (line.startsWith('#') ? `// ${line.slice(2)}` : `// ${line}`))
        .join('\n');
    const doc = `${header}\n${body}\n\n// Notes\n` +
        '// - cpu_ms is frame start to submit-return: the batcher CPU cost, and the\n' +
        '//   number `docs/modules/2d.md` §5 quotes. total_ms adds SDL_WaitForGPUIdle.\n' +
        '// - net_cpu_ms subtracts a measured empty-frame baseline (acquire, clear,\n' +
        '//   submit, wait with no draw), so it is the marginal cost of the bucket\n' +
        '//   rather than the fixed cost of a frame.\n' +
        '// - Check vulkan_icd above before treating total_ms as a hardware figure.\n' +
        '//   A software ICD (dzn, lavapipe, swiftshader) makes it a fill-rate\n' +
        '//   measurement of the host CPU, not of a GPU.\n' +
        '// - Median of 31 frames after 10 warm-up frames, per N.\n' +
        '// - nonblack_px is the smoke test: a fast frame that drew nothing would\n' +
        '//   be a broken bench, so the probe exits non-zero if it is 0.\n';
    writeFileSync(join(BENCH, 'results.txt'), doc);
    console.log(`wrote   ${join(BENCH, 'results.txt')}`);
}
