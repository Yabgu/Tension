#!/usr/bin/env node
// test.mjs — run hello-sprites and assert the frame it produced.
//
// This assertion used to live in a script under `scripts/` that ran the example
// and read its output. That launcher existed for one reason its own header
// states: **the assertion**. `tension-core` exits 0
// whether the guest drew ten sprites or nothing at all — the host has no idea
// what a correct frame looks like. Something has to read the output and decide.
//
// The launcher also did four things that were not its job: it found the
// capability DSO, set `LD_LIBRARY_PATH`-adjacent state, picked a video driver,
// and ran a C++ stub suite first. All of that went away with the DSO. What is
// left is the assertion, and it belongs beside the example it asserts.
//
// # The three checks, and why the number is hard-coded
//
//   1. `tension-core` exits 0.
//   2. the guest printed a pixel count,
//   3. the guest printed `OK: ten sprites at their recorded positions`, and
//   4. that count is **10240** — 10 sprites × 32×32.
//
// The guest also prints what it expects, and that line is deliberately not the
// reference: it is computed from the same `SPRITE_SIZE` that produced the frame,
// so changing both makes a self-consistent guest pass while drawing something
// else. Measured once — setting `SPRITE_SIZE` to 48 made the guest report
// "23040, expected 23040", and a checker that trusted it believed the frame.
// 10240 is the number the C++ stub asserted (`tension-2d/tests/smoke_core.cpp`,
// now deleted), and it does not move.
//
// The per-sprite position check is the guest's own: it samples each sprite's
// centre against `CELL_COLOURS` and prints `sprite N at (...) is (...)` for each
// miss. `OK:` is only printed when that count is zero, so check 3 covers check
// 4's ground — and a failure prints the guest's own lines rather than a
// paraphrase.
//
// Exit codes: 0 pass, 1 fail. No skip: the tileset is generated by the guest
// itself (it synthesises an atlas, it does not load one).
//
//   npm test              assert, headless
//   npm start             just run it, in a window (no assertion)
//   node test.mjs --show  assert, then hold the frame in a window
//
// The GPU note: on a machine where `vkCreateGraphicsPipelines` fails, this
// failure is environmental and the message says so. See
// `docs/known-limitations.md`.

import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const RUNNER = 'hello-sprites';

/// Whether a missing capability may be skipped, by the tree's one flag.
///
/// `TENSION_TEST_ALLOW_SKIP=1` — the same variable `tests/support/ci.rs` honours
/// for the Rust suites. A GPU that cannot create a pipeline is a missing
/// capability like any other, and it does not get its own spelling.
function supportSkip() {
  return process.env.TENSION_TEST_ALLOW_SKIP === '1';
}
const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..', '..', '..');
const WIN = process.platform === 'win32';
const EXE = WIN ? '.exe' : '';

function die(message) {
  console.error(`${RUNNER}: ${message}`);
  process.exit(1);
}

function run(cmd, args, opts = {}) {
  const result = spawnSync(cmd, args, { encoding: 'utf8', ...opts });
  if (result.error) return null;
  return result;
}

// ── 1. the renderer's shader modules ────────────────────────────────────────
//
// Since Pass B of the 2D merge the renderer is in core and `scripts/build-2d.mjs`
// produces shader modules and the graph blob, not a DSO. It still has to run:
// the walker's `default_2d` blob is compared against the modules it emits, and a
// missing blob leaves `set_pipeline` with nothing to resolve.
if (!existsSync(join(repo, 'tension-2d', 'build', 'shaders', 'default_2d.vert.spv'))) {
  console.log(`${RUNNER}: no shader modules, building them...`);
  const built = run('node', [join(repo, 'scripts', 'build-2d.mjs')], {
    stdio: 'inherit',
    cwd: repo,
  });
  if (!built || built.status !== 0) die('the shader modules did not build');
}

// ── 2. the guest ────────────────────────────────────────────────────────────
const guestBuild = run('node', [join(repo, 'scripts', 'build-2d-guest.mjs')], {
  stdio: 'inherit',
  cwd: here,
});
if (!guestBuild || guestBuild.status !== 0) die('the guest did not build');

// ── 3. tension-core ─────────────────────────────────────────────────────────
//
// The same resolution order as every other runner in this tree: an explicit
// `TENSION_CORE` wins, then the debug build, then the release build. A developer
// iterating on the renderer has the debug binary; a packaged checkout has the
// release one.
function findCore() {
  if (process.env.TENSION_CORE && existsSync(process.env.TENSION_CORE)) {
    return process.env.TENSION_CORE;
  }
  for (const profile of ['debug', 'release']) {
    const candidate = join(repo, 'tension-core', 'target', profile, `tension-core${EXE}`);
    if (existsSync(candidate)) return candidate;
  }
  return null;
}
const core = findCore();
if (!core) {
  die(
    `no tension-core\n` +
      `  Run \`cargo build --manifest-path tension-core/Cargo.toml\` first.`,
  );
}

// The bisect path. A `--no-default-features` binary has no `tension::2d` imports
// at all, so the guest cannot instantiate against it; the only thing that can
// answer them is the DSO built from `tension-2d/reference/`. Pass it only when
// one exists — an in-core run must not be handed a capability it would skip.
const dso = join(repo, 'tension-2d', 'build', WIN ? 'libtension_2d.dll' : 'libtension_2d.so');
const capabilityArgs = existsSync(dso) ? ['--capability', dso] : [];

// ── 4. run it headless ──────────────────────────────────────────────────────
//
// Headless is not a lesser mode here, it is the mode the assertion needs: a
// pixel claim has to be reproducible, and a compositor makes it depend on the
// machine. `offscreen` is a real video backend with a GPU, so the frame is the
// same one a window would show (`docs/modules/2d.md` §6 — `dummy` would not be).
//
// No `--window`: the guest asks for one itself when `--windowed` (or `--window`)
// is passed, which this run does not pass — the assertion needs `offscreen`.
const result = run(core, [...capabilityArgs, join(here, 'build', 'game.wasm')], {
  stdio: ['ignore', 'pipe', 'pipe'],
  cwd: here,
  env: { ...process.env, SDL_VIDEODRIVER: 'offscreen' },
});
if (!result) die('could not start tension-core');

const output = `${result.stdout ?? ''}${result.stderr ?? ''}`;

// The guest's own lines are the interesting ones. The host's INFO lines are
// noise for someone who ran `npm test` and wants to know whether it worked.
for (const line of (result.stdout ?? '').split('\n')) {
  if (line.trim()) console.log(`  ${line}`);
}

// ── 5. the assertions ───────────────────────────────────────────────────────
//
// **A GPU refusal is checked before the guest's output is judged**, because it
// makes the guest's output meaningless: the guest stops at `set_pipeline` and
// prints a "-5" line that says nothing about whether the port is right. Naming
// the environmental cause is the difference between a reader rebuilding their
// driver stack and a reader chasing a bug that is not there.
const gpu = output.match(/vkCreateGraphicsPipeline[s]?\s+(VK_\w+)/);
if (gpu || /set_pipeline -> -5/.test(output)) {
  const why = gpu ? gpu[1] : 'pipeline creation refused';
  const message =
    `this machine could not create a graphics pipeline (${why}).\n` +
    `  That is the driver, not the example: the pre-port C++ renderer fails the ` +
    `same way on the same rig.\n` +
    `  What would run on a conformant Vulkan ICD: ten sprites, 10240 non-black ` +
    `pixels, and \`OK: ten sprites at their recorded positions\`.\n` +
    `  CI's lavapipe provides one; see docs/known-limitations.md.`;
  if (supportSkip()) {
    console.log(`${RUNNER}: SKIP — ${message}`);
    process.exit(0);
  }
  die(message);
}

if (result.status !== 0) {
  console.error(result.stderr ?? '');
  die(`tension-core exited ${result.status}`);
}

const count = output.match(/screenshot -> \d+ bytes, (\d+) non-black pixels/);
if (!count) {
  console.error(output);
  const said = output.split('\n').find((line) => line.startsWith(`${RUNNER}: `) && !line.includes('PASS'));
  die(
    said
      ? `the guest stopped early: ${said.trim()}`
      : 'the guest printed no pixel count',
  );
}

const drawn = Number(count[1]);
const want = 10240; // 10 sprites x 32x32
const verdict = output.includes('OK: ten sprites at their recorded positions');

if (!verdict) {
  // The guest prints one `sprite N at (x,y) is (r,g,b), expected (...)` line per
  // miss, immediately above the FAILED line. Those are the failure; this adds
  // only the count, which the guest does not correlate with them.
  const misses = output.split('\n').filter((line) => /^\s*sprite \d+ at /.test(line));
  if (misses.length) {
    console.error(`  ${misses.length} sprite(s) at the wrong colour (the guest's own lines above)`);
  }
  die(`the guest did not print its OK line (drew ${drawn} non-black pixels)`);
}

if (drawn !== want) {
  die(`the guest drew ${drawn} non-black pixels, expected ${want} (10 x 32x32)`);
}

console.log(`${RUNNER}: ${drawn} non-black pixels — matches the C++ stub's count`);
console.log(`${RUNNER}: PASS`);

// ── 6. optionally show it ───────────────────────────────────────────────────
//
// `npm start` runs the binary directly and does not come through here, so this
// is for someone who ran `npm test --show` and wants to see what passed.
const argv = process.argv.slice(2);
if (!argv.includes('--show')) process.exit(0);

const hasDisplay =
  process.platform !== 'linux' || Boolean(process.env.DISPLAY || process.env.WAYLAND_DISPLAY);
if (!hasDisplay) {
  console.log(`${RUNNER}: --show asked for, but there is no display; nothing to open`);
  process.exit(0);
}

console.log(`${RUNNER}: showing the frame — close the window to exit`);
const shown = spawnSync(core, [...capabilityArgs, join(here, 'build', 'game.wasm'), '--windowed'], {
  stdio: 'inherit',
  cwd: here,
});
if (shown.error) console.error(`${RUNNER}: could not show the window: ${shown.error.message}`);
