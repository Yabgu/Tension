/// Write the pages and the scene table into `exampleDir`. Returns the scene
/// object, so a caller that also wants the probes does not re-derive them.
export function emit(exampleDir) {
  const s = scene();
  const pages = buildPages();

  // Replace, not merge: a page left over from an earlier scene (the real
  // example's `tileset_p0.iwi`, say) would otherwise be packed into the volume
  // and never read, which is 4 MB of confusion per stale page.
  rmSync(pageDir(exampleDir), { recursive: true, force: true });
  mkdirSync(pageDir(exampleDir), { recursive: true });
  mkdirSync(join(exampleDir, 'src'), { recursive: true });

  for (let i = 0; i < PAGE_COUNT; i++) {
    writeFileSync(join(pageDir(exampleDir), s.pages[i].name), iwi(pages[i], PAGE, PAGE));
  }
  writeFileSync(join(exampleDir, 'src', 'scene.generated.ts'), sceneTable(s));
  return s;
}

// ── CLI ─────────────────────────────────────────────────────────────────────

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const exampleDir = resolve(process.argv[2] ?? join(here, '..', 'isometric'));
  const s = emit(exampleDir);
  console.log(
    `emit: ${s.pages.map((p) => p.name).join(', ')} + src/scene.generated.ts -> ${exampleDir}`,
  );
}
