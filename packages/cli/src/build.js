// The three steps that turn a project into a runnable guest: the 2D graph
// blob, the compile, and the volume.
//
// Each step is a function of the resolved project, so `dev` and `build` share
// them and neither can drift from the other. `dev` runs them on every change;
// `build` runs them once and then copies the result somewhere self-contained.

import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { bytes, capture, die, exists, run, step } from './util.js';

/**
 * Create the directories a build writes into.
 *
 * `build/` is scratch and `src/` already exists (the entry lives in it), so this
 * is the one place that knows a build needs somewhere to put its output.
 */
export function ensureDirs(paths) {
  mkdirSync(paths.buildDir, { recursive: true });
  mkdirSync(dirname(paths.wasm), { recursive: true });
}

/**
 * Write `build/asconfig.json`, the compiler's resolved configuration.
 *
 * Written into `build/` rather than kept in memory for two reasons: a hand-run
 * `tensionscript --config build/asconfig.json` must reproduce the CLI's build,
 * and the VS Code AssemblyScript extension reads an asconfig from disk. It is
 * generated, so it is never a second source of truth — `sessionAsconfig` is.
 */
export function writeAsconfig(paths, asconfig) {
  const text = `${JSON.stringify(asconfig, null, 2)}\n`;
  if (exists(paths.asconfig) && readFileSync(paths.asconfig, 'utf8') === text) return false;
  writeFileSync(paths.asconfig, text);
  return true;
}

/**
 * Emit the `default_2d` graph blob the adapter was built against, as a
 * TypeScript literal the guest can carry.
 *
 * Two facts make this the CLI's job rather than the framework's:
 *
 *   1. A guest cannot read a file at run time, so the blob has to be compiled
 *      in. It arrives as a `u8[]` literal, exactly as
 *      `scripts/build-2d-guest.mjs` produces it for the repository's examples.
 *   2. The adapter embeds the modules for **one** hash. Bytes from a different
 *      emission get `-ENOSYS` at `set_pipeline`, so the blob must come from the
 *      host that will run it — `tension-core graph emit-default` — and not from
 *      a copy in a package that versions independently of the runtime.
 *
 * The file is only written when it changes. The dev loop watches `src/`, so
 * rewriting an identical file on every rebuild would restart the game for no
 * reason and recompile the guest for no reason.
 */
export function emitGraph(ctx) {
  if (ctx.config.renderer !== '2d') return { wrote: false, bytes: 0 };

  mkdirSync(ctx.paths.graphDir, { recursive: true });
  // Captured rather than inherited: the host prints a hash line per graph it
  // emits, and two lines of that on every save is noise in a dev loop. A
  // failure still prints everything it said.
  const emitted = capture(ctx.rt.host, ['graph', 'emit-default', '--out', ctx.paths.graphDir]);
  if (emitted.status !== 0) {
    die('tension-core could not emit the 2D graph blob',
      emitted.stderr.trim() || `exit ${emitted.status}`);
  }

  const blobPath = join(ctx.paths.graphDir, 'default_2d.t2dg');
  if (!exists(blobPath)) {
    die(`tension-core did not write ${blobPath}`, 'that is a bug in the host, not in this project');
  }
  const blob = readFileSync(blobPath);
  const hex = [...blob].map((b) => `0x${b.toString(16).padStart(2, '0')}`);
  const rows = [];
  for (let i = 0; i < hex.length; i += 12) rows.push(`  ${hex.slice(i, i + 12).join(', ')},`);

  const text =
    `// Generated by the tension CLI — do not edit.\n` +
    `//\n` +
    `// The \`default_2d\` graph blob, ${blob.length} bytes, emitted by the host that\n` +
    `// will run this guest (\`tension-core graph emit-default\`). The adapter embeds\n` +
    `// the modules for this blob's FNV-1a hash; a guest that sends other bytes gets\n` +
    `// -ENOSYS from set_pipeline.\n` +
    `\n` +
    `/** The T2DG blob, byte for byte. */\n` +
    `export const DEFAULT_2D_BLOB: u8[] = [\n${rows.join('\n')}\n];\n`;

  if (exists(ctx.paths.generated) && readFileSync(ctx.paths.generated, 'utf8') === text) {
    return { wrote: false, bytes: blob.length };
  }
  mkdirSync(dirname(ctx.paths.generated), { recursive: true });
  writeFileSync(ctx.paths.generated, text);
  return { wrote: true, bytes: blob.length };
}

/**
 * Compile the guest.
 *
 * `--config` is not a preference: the guest imports its memory and the arena
 * starts at address 0, which is what makes `guest_read` legal for a capability.
 * A guest built without it exports its own memory, the session still opens, and
 * every verb that touches guest memory answers `-EBADF`.
 */
export function compileGuest(ctx, { debug = false } = {}) {
  const args = [
    ...ctx.compiler.prefix,
    ctx.paths.entry,
    '--config', ctx.paths.asconfig,
    ...(debug ? ['--debug', '--sourceMap'] : []),
    '-o', ctx.paths.wasm,
  ];
  const status = run(ctx.compiler.command, args, { cwd: ctx.projectDir });
  if (status !== 0) return { ok: false };
  return { ok: true, bytes: statSync(ctx.paths.wasm).size };
}

/**
 * Pack the asset tree into one volume.
 *
 * `tension-core pack` rather than the repository's Zig packer, and the two
 * produce byte-identical output (verified on `examples/ogre/hello-mesh`: same
 * 9728 bytes, `cmp` clean). The reason to prefer the host is that the host is
 * already resolved and already shipped — a project should not need a second
 * native tool, and a user should not be told to run a build script in a
 * repository they do not have.
 */
export function packAssets(ctx) {
  if (!ctx.paths.assetsDir) return null;
  if (!exists(ctx.paths.assetsDir)) {
    die(`assets.dir names a directory that does not exist: ${ctx.paths.assetsDir}`, [
      'tension.config.json declares assets, so the tree must be there',
      'remove the `assets` key from the config if this project has no assets',
    ]);
  }
  mkdirSync(dirname(ctx.paths.volume), { recursive: true });
  const packed = capture(ctx.rt.host, ['pack', ctx.paths.assetsDir, '-o', ctx.paths.volume]);
  if (packed.status !== 0) {
    die('packing the assets failed', packed.stderr.trim() || `exit ${packed.status}`);
  }
  return { path: ctx.paths.volume, bytes: statSync(ctx.paths.volume).size };
}

/**
 * Everything up to a runnable host: config on disk, graph blob, wasm, volume.
 *
 * Returns what to print and what to spawn, so the caller decides whether a
 * failure is fatal (`build`) or survivable (`dev` keeps watching).
 */
export function buildOnce(ctx, { debug = false, quiet = false } = {}) {
  const started = Date.now();
  ensureDirs(ctx.paths);

  const asconfig = ctx.sessionAsconfig;
  writeAsconfig(ctx.paths, asconfig);

  const graph = emitGraph(ctx);
  const compiled = compileGuest(ctx, { debug });
  if (!compiled.ok) return { ok: false, stage: 'compile' };

  const volume = packAssets(ctx);

  const elapsed = Date.now() - started;
  if (!quiet) {
    step(`tension: built ${short(ctx.projectDir, ctx.paths.wasm)} ` +
      `(${bytes(compiled.bytes)})${volume ? ` + ${short(ctx.projectDir, volume.path)} ` +
      `(${bytes(volume.bytes)})` : ''} in ${elapsed} ms`);
    if (graph.wrote) step(`tension: emitted src/graph.generated.ts (${graph.bytes} bytes)`);
  }
  return { ok: true, wasm: compiled.bytes, volume, elapsed };
}

/// A path as the log should show it: relative to the project when it is inside.
function short(from, to) {
  if (!to.startsWith(from)) return to;
  return to.slice(from.length + 1).split('\\').join('/');
}
