/**
 * @fileoverview The `graph.generated.ts` module, rendered from a T2DG blob.
 *
 * **Two legitimate producers write this file**, and they must keep saying which
 * one wrote it — that is provenance, and a reader debugging a stale blob needs it:
 *
 *   `scripts/build-2d-guest.mjs`  from the checked-in `tension-2d/tests/default_2d.t2dg`
 *   `packages/cli/src/build.js`   from `tension-core graph emit-default`
 *
 * So byte-stability across the two is the **wrong goal** — the comment lines
 * differ by design. What must not differ is everything else: the hex rows, their
 * wrapping, the `u8[]` shape, the trailing comma. That part was copy-pasted, and
 * a change to the wrap width in one copy would silently churn the other's output.
 * Rendering it here means the only line either producer can vary is the one that
 * says who it was.
 *
 * **Why this lives in the CLI package.** `packages/cli` is published and cannot
 * import `scripts/`, so the shared code has to sit on the shipped side; the repo
 * script imports it from here. Same direction and same reason as
 * `compiler-provenance.js` — one implementation, on the side that travels.
 */

/** Bytes per rendered line. Twelve fits comfortably and keeps the file diffable. */
const PER_ROW = 12;

/**
 * Render the module.
 *
 * `provenance` is the comment block **below** the "do not edit" line, one entry
 * per line, without the `// ` prefix. Callers pass what they know: where the blob
 * came from and what a mismatch costs. The generator name goes in the first line
 * and is the caller's (`generator`), because that is the one fact that differs.
 */
export function renderGraphBlobModule({ blob, generator, provenance }) {
  const hex = [...blob].map((byte) => `0x${byte.toString(16).padStart(2, '0')}`);
  const rows = [];
  for (let i = 0; i < hex.length; i += PER_ROW) {
    rows.push(`  ${hex.slice(i, i + PER_ROW).join(', ')},`);
  }

  const comment = [
    `// Generated by ${generator} — do not edit.`,
    '//',
    ...provenance.map((line) => (line ? `// ${line}` : '//')),
  ].join('\n');

  return `${comment}\n` +
    '\n' +
    '/** The T2DG blob, byte for byte. */\n' +
    `export const DEFAULT_2D_BLOB: u8[] = [\n${rows.join('\n')}\n];\n`;
}
