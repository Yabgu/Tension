const ROWS = 16;
const COLS = 8;

/**
 * The glyph table, parsed and validated.
 *
 * `index` is the character's code minus 32, which is also its position in the
 * atlas stripe: the viewer converts a character to a cell with one subtraction
 * and no lookup table.
 */
export const GLYPHS = (() => {
  const chars = Object.keys(RAW);
  if (chars.length !== 95) {
    throw new Error(`font8x16: ${chars.length} glyphs defined, 95 required (ASCII 32..126)`);
  }

  const glyphs = [];
  for (let code = 32; code <= 126; code++) {
    const ch = String.fromCharCode(code);
    const spec = RAW[ch];
    if (!spec) throw new Error(`font8x16: no glyph for ${JSON.stringify(ch)} (U+${code.toString(16)})`);

    const rows = spec.split('/');
    if (rows.length !== ROWS) {
      throw new Error(`font8x16: ${JSON.stringify(ch)} has ${rows.length} rows, expected ${ROWS}`);
    }

    // One byte per pixel, 0 or 1. A packed bitmap would be 16 bytes per glyph
    // instead of 128, but the baker indexes a mask per pixel and unpacking here
    // would be work for no benefit at build time.
    const mask = new Uint8Array(ROWS * COLS);
    for (let y = 0; y < ROWS; y++) {
      const row = rows[y];
      if (row.length !== COLS) {
        throw new Error(`font8x16: ${JSON.stringify(ch)} row ${y} has ${row.length} columns, expected ${COLS}`);
      }
      for (let x = 0; x < COLS; x++) {
        const c = row[x];
        if (c !== '#' && c !== '.') {
          throw new Error(`font8x16: ${JSON.stringify(ch)} row ${y} has '${c}', expected '#' or '.'`);
        }
        mask[y * COLS + x] = c === '#' ? 1 : 0;
      }
    }
    glyphs.push({ char: ch, code, index: code - 32, mask });
  }
  return glyphs;
})();

/** Look a character up, or `null` when the font has no glyph for it. */
export function glyphFor(ch) {
  const code = ch.codePointAt(0);
  if (code < 32 || code > 126) return null;
  return GLYPHS[code - 32];
}

/**
 * Where the baseline sits, so layout arithmetic and this table cannot disagree.
 *
 * The viewer positions a line by its baseline, which makes these numbers layout
 * constants rather than font trivia. They are exported next to the data that
 * makes them true and re-exported through `assets/ui.json`.
 */
export const BASELINE_ROW = 11;
/** The first row a capital or ascender may use. */
export const ASCENT_ROW = 2;
/** Rows below the baseline a descender may occupy. */
export const DESCENT_ROWS = 2;

export { ROWS, COLS };
