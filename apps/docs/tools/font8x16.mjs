const ROWS = 16;
const COLS = 8;

/**
 * Where the baseline sits, so layout arithmetic and this table cannot disagree.
 *
 * The viewer positions a line by its baseline, which makes these numbers layout
 * constants rather than font trivia. They are declared here, above the table, so
 * `assertMetrics` can enforce them as the table is built — and re-exported
 * through `assets/ui.json` for anything that draws from the other side.
 */
export const BASELINE_ROW = 11;
/** The row ascenders (`b d f h k l t`) start on. Capitals start one row lower:
 *  a capital is 9 rows tall and an ascender 10, which is what distinguishes
 *  `b` from `B` at this size. */
export const ASCENT_ROW = 2;
/** Rows below the baseline a descender may occupy. */
export const DESCENT_ROWS = 2;

/** Lowercase letters that occupy the x-height band. */
const X_HEIGHT = 'acemnorsuvwxz';
/** Lowercase letters whose stem reaches the ascender row. */
const ASCENDERS = 'bdfhklt';
/** Lowercase letters that hang below the baseline. */
const DESCENDERS = 'gjpqy';
/** Capitals and digits, which occupy the cap band. */
const CAPITALS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
/** The letters wide enough to need the cell's last column. */
const WIDE = 'mwMW';


/**
 * The glyph table, parsed and validated.
 *
 * `index` is the character's code minus 32, which is also its position in the
 * atlas stripe: the viewer converts a character to a cell with one subtraction
 * and no lookup table.
 */
export const GLYPHS = (() => {
  const chars = Object.keys(RAW);
  if (chars.length !== 95) {
    throw new Error(`font8x16: ${chars.length} glyphs defined, 95 required (ASCII 32..126)`);
  }

  const glyphs = [];
  for (let code = 32; code <= 126; code++) {
    const ch = String.fromCharCode(code);
    const spec = RAW[ch];
    if (!spec) throw new Error(`font8x16: no glyph for ${JSON.stringify(ch)} (U+${code.toString(16)})`);

    const rows = spec.split('/');
    if (rows.length !== ROWS) {
      throw new Error(`font8x16: ${JSON.stringify(ch)} has ${rows.length} rows, expected ${ROWS}`);
    }

    // One byte per pixel, 0 or 1. A packed bitmap would be 16 bytes per glyph
    // instead of 128, but the baker indexes a mask per pixel and unpacking here
    // would be work for no benefit at build time.
    const mask = new Uint8Array(ROWS * COLS);
    for (let y = 0; y < ROWS; y++) {
      const row = rows[y];
      if (row.length !== COLS) {
        throw new Error(`font8x16: ${JSON.stringify(ch)} row ${y} has ${row.length} columns, expected ${COLS}`);
      }
      for (let x = 0; x < COLS; x++) {
        const c = row[x];
        if (c !== '#' && c !== '.') {
          throw new Error(`font8x16: ${JSON.stringify(ch)} row ${y} has '${c}', expected '#' or '.'`);
        }
        mask[y * COLS + x] = c === '#' ? 1 : 0;
      }
    }
    glyphs.push({ char: ch, code, index: code - 32, mask });
  }
  assertMetrics(glyphs);
  return glyphs;
})();

// ── the metrics, enforced ───────────────────────────────────────────────────
//
// The comment at the top of this file describes where every class of glyph must
// sit. These are the same claims as code, because a font table drifts silently:
// the version before this check had all 36 capitals and digits landing on row 10
// while every lowercase letter landed on 11, and nothing said so.

/** Every row and column a glyph touches, or `null` for a blank glyph. */
function inkBounds(mask) {
  let top = -1, bottom = -1, left = COLS, right = -1;
  for (let y = 0; y < ROWS; y++) {
    for (let x = 0; x < COLS; x++) {
      if (!mask[y * COLS + x]) continue;
      if (top < 0) top = y;
      bottom = y;
      if (x < left) left = x;
      if (x > right) right = x;
    }
  }
  return top < 0 ? null : { top, bottom, left, right };
}

/**
 * Refuse a glyph table that breaks the metrics this file documents.
 *
 * Called once, at load. Every failure names the glyph and the row, because the
 * useful part of this error is *which* letter moved — a font is data, and a data
 * error without a coordinate is a scavenger hunt.
 */
function assertMetrics(glyphs) {
  const problems = [];
  const fail = (ch, why) => problems.push(`'${ch}': ${why}`);

  for (const { char: ch, mask } of glyphs) {
    const b = inkBounds(mask);
    if (b === null) continue; // the space is legitimately blank

    // A pixel of bearing on the left, at least. Ink in column 0 touches the
    // previous character; whether the right edge may use column 7 is the one
    // per-glyph exception this font allows.
    if (b.left === 0) fail(ch, 'ink in column 0 (no left bearing)');
    if (b.right === COLS - 1 && !WIDE.includes(ch)) {
      fail(ch, 'ink in column 7 (only ' + WIDE + ' may be that wide)');
    }
    if (b.top < ASCENT_ROW) fail(ch, `ink at row ${b.top}, above the ascent row ${ASCENT_ROW}`);
    if (b.bottom > BASELINE_ROW + DESCENT_ROWS) {
      fail(ch, `ink at row ${b.bottom}, below the descent ${BASELINE_ROW + DESCENT_ROWS}`);
    }

    // The baseline is the one rule a reader notices immediately, because a
    // capital that misses it floats above the word it belongs to.
    if (CAPITALS.includes(ch) && b.bottom !== BASELINE_ROW) {
      fail(ch, `cap/digit bottom row ${b.bottom}, baseline is ${BASELINE_ROW}`);
    }
    if (X_HEIGHT.includes(ch) && b.bottom !== BASELINE_ROW) {
      fail(ch, `x-height bottom row ${b.bottom}, baseline is ${BASELINE_ROW}`);
    }
    if (ASCENDERS.includes(ch)) {
      if (b.top !== ASCENT_ROW) fail(ch, `ascender top row ${b.top}, ascent is ${ASCENT_ROW}`);
      if (b.bottom !== BASELINE_ROW) fail(ch, `ascender bottom row ${b.bottom}, baseline is ${BASELINE_ROW}`);
    }
    if (DESCENDERS.includes(ch) && b.bottom <= BASELINE_ROW) {
      fail(ch, `descender bottom row ${b.bottom} does not pass the baseline ${BASELINE_ROW}`);
    }
  }

  if (problems.length) {
    throw new Error('font8x16: the glyph table breaks its own metrics:\n  ' +
      problems.join('\n  '));
  }
}

/** Look a character up, or `null` when the font has no glyph for it. */
export function glyphFor(ch) {
  const code = ch.codePointAt(0);
  if (code < 32 || code > 126) return null;
  return GLYPHS[code - 32];
}

