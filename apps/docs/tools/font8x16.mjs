// The 8x16 bitmap font the documentation viewer draws with.
//
// **Why a hand-authored bitmap and not a TTF.** There is no font rasterizer in
// this tree, Python is deliberately not a repository dependency
// (`scripts/gen-session.mjs` says so at length), and the 2D sampler is
// `Filter::Nearest` — so an 8x16 bitmap scaled by an integer is *crisp* on
// screen, which is the whole reason bitmap fonts survive. A TTF would mean a new
// dependency, a rasterizer in the guest, and anti-aliased edges that nearest
// filtering would turn into mud.
//
// Each glyph is 16 rows of 8 characters. `#` is ink, `.` is paper. Glyphs are
// drawn in columns 1..6 of the 8-pixel cell, so a monospace 8-pixel advance
// leaves a pixel of bearing on each side and no two letters touch. The four
// letters that cannot be drawn that narrow — `m`, `w`, `M`, `W` — use column 7
// as well, which costs them their right bearing and buys the counter between
// two stems that makes them readable. What makes that safe is the baker:
// `blitMask` clamps bold dilation to the glyph's own cell, so a column-7 pixel
// thickens to column 8 *inside the cell* and never into the neighbour's.
//
// ## Metrics - one baseline, and every glyph obeys it
//
//     row 0-1    leading
//     row 2      ascenders only (b d f h k l t)
//     row 3      cap height (A-Z and 0-9)
//     row 5      x-height
//     row 11     **the baseline** - the bottom row of every cap, digit and
//                x-height letter
//     row 12-13  descenders (g j p q y) and the comma's tail
//
// This section used to be aspirational: it claimed row 11 was the baseline of
// caps, digits *and* x-height letters, while every capital and digit actually
// ended on row 10. One pixel is enough to make a page of text look wrong in a
// way nobody can name — capitals floated above the lowercase, and `T` sat
// visibly higher than the `o` beside it. `assertMetrics` below now refuses the
// table if any of this stops being true, which is the only reason the comment is
// worth reading.
//
// Ascenders reach one row above cap height, as they should: 10 rows of ascender
// against 9 of capital is what makes `b` and `B` different heights.
//
// A glyph with the wrong row or column count is refused at load rather than
// drawn short, because a font table is exactly the kind of data where one
// missing row shifts every glyph after it on the atlas.

