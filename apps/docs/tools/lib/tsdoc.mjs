// Scan the guest SDK's doc comments into Markdown reference pages.
//
// **Why a scanner and not the TypeScript compiler API.** The API would need a
// parser dependency and a `tsconfig` for a codebase that is not TypeScript —
// it is TensionScript, with `struct`, `@external` and `i32` as real syntax. The
// TypeScript compiler parses most of it and then reports errors on the rest, so
// the honest tool is a scanner that only has to find a comment and the
// declaration under it. That is ~120 lines and has no opinion about the body.
//
// **Why `tension-framework/index.d.ts` is not the source.** It says of itself
// that it "only describes part of the surface", it is hand-written, and it has
// 15 doc comments against the assembly sources' thousands of lines. The docs a
// reader wants are the ones the implementer wrote next to the code.
//
// The output is **generated Markdown**, and it is fed through the same lexer as
// the hand-written pages. One parser downstream, two front doors — which is what
// keeps the reference pages and the prose from drifting into different markdown
// dialects.

import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

/** Directories whose contents are generated and therefore not documented here. */
const SKIP_DIRS = new Set(['node_modules', 'build', 'generated', '.git']);

/** Files generated by `scripts/gen-session.mjs`; their prose is machine text. */
const SKIP_FILES = new Set(['layout.ts', 'manifest.ts']);

/**
 * A declaration this scanner understands.
 *
 * Deliberately shallow: a reference page is a list of top-level things with
 * their doc comment and signature. Members are inside the body, which this does
 * not read: a class's own doc comments reach the page through its
 * top-level declaration only, and that is a known limit.
 */
const DECLARATION = /^export\s+(?:declare\s+)?(?:abstract\s+)?(function|class|struct|enum|interface|const|let|type)\s+([A-Za-z_$][\w$]*)/;

const KIND_LABEL = {
  function: 'Functions',
  class: 'Classes',
  struct: 'Structs',
  enum: 'Enums',
  interface: 'Interfaces',
  const: 'Constants',
  let: 'Constants',
  type: 'Types',
};

/** Every `.ts` under `dir`, skipping generated trees. */
function walkTs(dir, out = []) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      walkTs(path, out);
      continue;
    }
    if (!entry.name.endsWith('.ts')) continue;
    if (SKIP_FILES.has(entry.name)) continue;
    out.push(path);
  }
  return out;
}

/** Strip the comment delimiters and the leading ` * ` from each line. */
function cleanComment(raw) {
  const body = raw.replace(/^\/\*\*/, '').replace(/\*\/$/, '');
  const lines = body.split('\n').map((line) => {
    const trimmed = line.replace(/^\s*\*/, '');
    // One space after the star is the convention; removing exactly one keeps
    // indented code blocks inside comments readable.
    return trimmed.startsWith(' ') ? trimmed.slice(1) : trimmed;
  });
  // Drop the blank first/last lines the delimiters leave behind.
  while (lines.length && lines[0].trim() === '') lines.shift();
  while (lines.length && lines[lines.length - 1].trim() === '') lines.pop();
  return lines.join('\n');
}

/**
 * Scan one file.
 *
 * Returns entries in source order. The scanner tracks the comment that
 * immediately precedes a declaration, allowing blank lines and other comments
 * between them, because that is how these files are written.
 */
function scanFile(path) {
  const text = readFileSync(path, 'utf8');
  const entries = [];
  // `[\s\S]` rather than `.` with `s`, so this works on any Node that can run
  // the rest of the repo's tooling.
  const commentRe = /\/\*\*[\s\S]*?\*\//g;
  let match;

  while ((match = commentRe.exec(text)) !== null) {
    const doc = cleanComment(match[0]);
    if (!doc.trim()) continue;

    // The declaration is the first non-blank, non-comment line after the block.
    const rest = text.slice(match.index + match[0].length);
    const lines = rest.split('\n');
    let kind = null;
    let name = null;
    let signatureStart = 0;

    for (let i = 0; i < lines.length && i < 30; i++) {
      const line = lines[i].trim();
      if (line === '') continue;
      if (line.startsWith('//') || line.startsWith('/*') || line.startsWith('*')) continue;
      // Decorators (`@external`, `@inline`) sit above the declaration.
      if (line.startsWith('@')) continue;

      const decl = DECLARATION.exec(line);
      if (decl) {
        kind = decl[1];
        name = decl[2];
        signatureStart = i;
        break;
      }
      // A doc comment followed by something that is not an exported declaration
      // is an internal note: skip it rather than inventing a page entry.
      break;
    }
    if (!name) continue;

    // The signature runs to the line that ends it — `{` for a block, `;` or a
    // complete one-liner for the rest.
    const sigLines = [];
    let depth = 0;
    for (let i = signatureStart; i < lines.length && sigLines.length < 12; i++) {
      const line = lines[i];
      sigLines.push(line.replace(/\s+$/, ''));
      for (const ch of line) {
        if (ch === '{' || ch === '(') depth++;
        else if (ch === '}' || ch === ')') depth--;
      }
      if (depth <= 0 && (line.includes('{') || line.trim().endsWith(';') || /\)\s*;?$/.test(line))) break;
    }
    // A body's opening brace is enough for a reader; the implementation is not
    // the reference.
    let signature = sigLines.join('\n').trim();
    const brace = signature.indexOf('{');
    if (brace > 0) signature = signature.slice(0, brace).trim();

    entries.push({ kind, name, signature, doc });
  }
  return entries;
}

/**
 * Build one Markdown page per source file that has documented declarations.
 *
 * @param {string} frameworkDir  `tension-framework/`
 * @param {string} [repoRoot]    for the displayed path
 * @returns {Array<{path:string, title:string, markdown:string}>}
 */
export function scanFramework(frameworkDir, repoRoot = frameworkDir) {
  const assembly = join(frameworkDir, 'assembly');
  const files = walkTs(assembly).sort();
  const pages = [];

  for (const file of files) {
    const entries = scanFile(file);
    if (!entries.length) continue;

    const shown = relative(repoRoot, file).split('\\').join('/');
    const moduleName = shown
      .replace(/^tension-framework\/assembly\//, '')
      .replace(/\.ts$/, '');

    // Group by declaration kind so a reader sees functions together, rather
    // than in the order the file happens to interleave them.
    const groups = new Map();
    for (const entry of entries) {
      const label = KIND_LABEL[entry.kind] ?? 'Other';
      if (!groups.has(label)) groups.set(label, []);
      groups.get(label).push(entry);
    }

    const parts = [`# \`${moduleName}\``, '', `Reference for \`${shown}\`, generated from the source's doc comments.`, ''];

    for (const [label, list] of groups) {
      parts.push(`## ${label}`, '');
      for (const entry of list) {
        parts.push(`### \`${entry.name}\``, '');
        parts.push('```ts', entry.signature, '```', '');
        parts.push(entry.doc, '');
      }
    }

    pages.push({
      // Sorted after `abi/` so the reference reads last in its chapter.
      path: `sdk/${moduleName.replace(/\//g, '-')}.md`,
      title: moduleName,
      markdown: parts.join('\n'),
    });
  }
  return pages;
}
